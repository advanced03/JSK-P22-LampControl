(function () {
  const supportedLanguages = Object.keys(translations);
  let currentLanguage = 'en';

  function translate(key, values = {}) {
    let template = translations[currentLanguage][key];
    if (template === undefined) {
      template = translations.en[key];
      if (template === undefined) {
        console.error(`Missing Ambilight translation: ${key}`);
        template = key;
      } else if (currentLanguage !== 'en') {
        console.warn(`Missing ${currentLanguage} Ambilight translation for "${key}"; using English.`);
      }
    }
    return template.replace(/\{(\w+)\}/g, (_match, name) => (
      values[name] === undefined ? `{${name}}` : String(values[name])
    ));
  }

  function applyTranslations() {
    document.querySelectorAll('[data-ambi-i18n]').forEach(element => {
      element.textContent = translate(element.dataset.ambiI18n);
    });
    document.querySelectorAll('[data-ambi-i18n-aria-label]').forEach(element => {
      element.setAttribute('aria-label', translate(element.dataset.ambiI18nAriaLabel));
    });
  }

  window.ambiI18n = {
    translate,
    setLanguage(language) {
      if (!supportedLanguages.includes(language)) {
        console.warn(`Unsupported Ambilight language: ${language}`);
        currentLanguage = 'en';
      } else {
        currentLanguage = language;
      }
      applyTranslations();
    },
    getLanguage() {
      return currentLanguage;
    }
  };

  applyTranslations();
})();
