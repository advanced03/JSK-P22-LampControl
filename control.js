    let gattQueue = Promise.resolve()
    function gatt(operation) {
      const result = gattQueue.then(operation)
      gattQueue = result.catch(() => {})
      return result
    }
    async function send(bytes) {
      if (!ambilightSending && window.ambilight) {
        window.ambilight.stop()
      }
      pending = bytes
      if (busy || !ch) return
      busy = true
      try {
        while (pending) {
          const b = pending
          pending = null
          await gatt(() => ch.writeValueWithoutResponse(new Uint8Array(b)))
          await new Promise((r) => setTimeout(r, 40))
        }
      } catch (e) {
        reportConnectionError('connection.writeFailed', e)
      }
      busy = false
    }
